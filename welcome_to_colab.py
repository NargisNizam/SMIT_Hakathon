import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
df = pd.read_excel("SalesReport1.xlsx")
print(df.head(20))

"""#Data Clean"""

df.isnull().sum()

"""#Fix Missing values."""

quarter_cols = ["Qtr 1", "Qtr 2", "Qtr 3", "Qtr 4"]

df[quarter_cols] = df[quarter_cols].fillna(df[quarter_cols].mean())

"""#Data Type"""

df.dtypes

"""#Detect and treat outliers"""

def detect_outliers(col):
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    return df[(df[col] < lower) | (df[col] > upper)]

"""# Data Analyses"""

df[quarter_cols].agg(["mean", "min", "max"])

"""#Top 5 Customers"""

df["Total_Sales"] = df[quarter_cols].sum(axis=1)

df.sort_values("Total_Sales", ascending=False).head(5)

"""#Low Sale record"""

df[df["Total_Sales"] < 500]

"""#Quarter Averige"""

df [quarter_cols].mean()

"""# Data Visualization
#Line Plot
"""

quarters = ["Qtr 1", "Qtr 2", "Qtr 3", "Qtr 4"]
customers = df["Customer"].unique()
plt.figure(figsize=(10,6))
for customer in customers:
    cust_data = df[df["Customer"] == customer]
    y_values = cust_data[quarters].sum()
    plt.plot(quarters, y_values, marker='o', label=customer)

plt.xlabel("Quarter")
plt.ylabel("Sales / Amount")
plt.title("Customer Quarterly Sales")
plt.show()

